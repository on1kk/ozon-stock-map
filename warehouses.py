def normalize(name: str) -> str:
    return (name or "").upper().replace("Ё", "Е").strip()


def _locate_in(table: dict, warehouse_name: str):
    n = normalize(warehouse_name)
    best = None
    for key, val in table.items():
        if key in n:
            if best is None or len(key) > best[0]:
                best = (len(key), val)
    return best[1] if best else None


