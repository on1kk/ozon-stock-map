def normalize(name: str) -> str:
    return (name or "").upper().replace("Ё", "Е").strip()


def locate(warehouse_name: str):
    """Вернёт (lat, lon, cluster, addr) или None, если склад не распознан."""
    n = normalize(warehouse_name)
    best = None
    for key, val in WAREHOUSE_COORDS.items():
        if key in n:
            if best is None or len(key) > best[0]:
                best = (len(key), val)
    return best[1] if best else None
